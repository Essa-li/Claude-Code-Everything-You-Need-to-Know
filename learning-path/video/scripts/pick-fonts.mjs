// Copies only the font subsets the video's text needs into public/fonts and
// writes src/fonts.gen.ts. Run before rendering: node scripts/pick-fonts.mjs
// (Rendering cannot fetch Google Fonts in this sandbox, so fonts are local.)
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const text = readdirSync(join(root, "src"))
  .filter((f) => /\.(tsx?|ts)$/.test(f) && f !== "fonts.gen.ts")
  .map((f) => readFileSync(join(root, "src", f), "utf8"))
  .join("");
const cps = new Set([...text].map((c) => c.codePointAt(0)));

const families = [
  { family: "Noto Sans SC", pkg: "@fontsource/noto-sans-sc", weights: [400, 700, 900] },
  { family: "JetBrains Mono", pkg: "@fontsource/jetbrains-mono", weights: [400, 700] },
];

function inRange(range) {
  return range.split(",").some((part) => {
    const m = part.trim().replace(/^U\+/i, "").split("-");
    const lo = parseInt(m[0].replace(/\?/g, "0"), 16);
    const hi = m[1] ? parseInt(m[1], 16) : parseInt(m[0].replace(/\?/g, "f"), 16);
    for (const cp of cps) if (cp >= lo && cp <= hi) return true;
    return false;
  });
}

const out = join(root, "public", "fonts");
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const faces = [];
for (const f of families) {
  for (const w of f.weights) {
    const cssPath = join(root, "node_modules", f.pkg, `${w}.css`);
    const css = readFileSync(cssPath, "utf8");
    for (const block of css.split("@font-face").slice(1)) {
      const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)?.[1];
      const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1]?.trim();
      if (!file || !range || !inRange(range)) continue;
      copyFileSync(join(root, "node_modules", f.pkg, "files", file), join(out, file));
      faces.push({ family: f.family, weight: String(w), file: `fonts/${file}`, range });
    }
  }
}
writeFileSync(
  join(root, "src", "fonts.gen.ts"),
  `// Generated by scripts/pick-fonts.mjs. Do not edit.\nexport const FACES = ${JSON.stringify(faces, null, 1)} as const;\n`,
);
console.log(`${faces.length} font files for ${cps.size} distinct characters`);
